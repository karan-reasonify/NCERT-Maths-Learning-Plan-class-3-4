# -*- coding: utf-8 -*-
"""Write the content briefs of a built Class 3/4 plan: briefs/videos.md, briefs/images.md, briefs/tools.md.

The briefs are generated from the plan's own media nodes (the single source of truth), so a brief can never disagree
with the plan. A node whose brief is still incomplete is written with a "TO DO" line naming what is missing; the
gate (gates/flow_c34.py) reports the same list as errors.

    write_briefs(plan, out_dir) -> {"videos": n, "images": n, "tools": n}
"""
from __future__ import annotations

import io
import os

from gates.media_content import walk_topics


def _bullet(label, value):
    if isinstance(value, (list, tuple)):
        value = ", ".join(str(v) for v in value)
    return "- **%s:** %s" % (label, value if value else "TO DO")


def _concepts(plan):
    return {c["concept_id"]: c for t in walk_topics(plan) for c in t.get("concepts") or []}


def _nodes(plan, kind):
    return [m for t in walk_topics(plan) for m in t.get("media") or [] if m.get("type") == kind]


def _head(plan, title):
    return ["# %s: %s" % (title, plan.get("chapter_name")),
            "",
            "Class %s, chapter %s. Generated by `build.py --briefs`; edit `concept_plan.py` / `topics_*.py` / `tools_*.py`, "
            "never this file." % (plan.get("grade"), plan.get("chapter_no")),
            ""]


def _videos(plan):
    cmap = _concepts(plan)
    lines = _head(plan, "Video story briefs")
    lines += ["Every video is a short STORY with the chapter's characters: a meaningful event or problem that leads to "
              "the concept. The hook introduces the situation only. A concept video continues the thread and explains "
              "one concept.", ""]
    for n in _nodes(plan, "video"):
        b = n.get("story_brief") or {}
        c = cmap.get(n["concept_id"], {})
        lines += ["## %s  %s (%s video, about %s s)" % (n["id"], n["title"], n["video_kind"], n.get("target_seconds") or "TO DO"),
                  "",
                  _bullet("Purpose", n.get("purpose")),
                  _bullet("Concept it explains", n.get("new_idea") if n["video_kind"] == "concept" else "none (hook)"),
                  _bullet("Characters", b.get("characters")),
                  _bullet("Setting", b.get("setting")),
                  _bullet("What happens", b.get("situation"))]
        if n["video_kind"] == "hook":
            lines.append(_bullet("Ends on the open question", b.get("open_question")))
        else:
            lines += [_bullet("The problem", b.get("problem")),
                      _bullet("Story thread (how it continues)", b.get("thread")),
                      _bullet("Continues from", n.get("continues_from")),
                      _bullet("Leads into", b.get("leads_to"))]
        lines += [_bullet("Concept", "%s (%s)" % (c.get("concept_name"), n["concept_id"])), ""]
    return "\n".join(lines)


def _images(plan):
    lines = _head(plan, "Image briefs")
    lines += ["Clean, minimal, real-life. An image is made only when it adds a real-life example or visual reference "
              "that no video or tool already shows. `pinned` images are supporting material, not part of the main "
              "sequence.", ""]
    for n in _nodes(plan, "image"):
        lines += ["## %s  %s (%s, %s)" % (n["id"], n["title"], n["placement"], n.get("style")), "",
                  _bullet("What it adds", n.get("adds")),
                  _bullet("Real-life subject", n.get("real_life")),
                  _bullet("What the child should notice", n.get("shows")),
                  _bullet("Short caption / prompt", n.get("caption")),
                  _bullet("Visuals drawn the same way as elsewhere", n.get("visuals")),
                  _bullet("Generation prompt", n.get("generation_prompt")), ""]
    if len(lines) <= 6:
        lines.append("_This chapter plans no images._")
    return "\n".join(lines)


def _tools(plan):
    lines = _head(plan, "Tool briefs")
    lines += ["The approved tool names, purposes and sequence are fixed by the content team. One learning objective, "
              "simple controls, large visuals, minimal text, helpful feedback.", ""]
    for n in _nodes(plan, "2d_tool"):
        c = n.get("tool_config") or {}
        lines += ["## Tool %s: %s  (%s)" % (c.get("approved_no"), n["tool_name"], n["id"]), "",
                  _bullet("Approved purpose (unchanged)", c.get("approved_purpose")),
                  _bullet("Where", "right after the hook" if c.get("role") == "explore" else
                          "after the concept video it applies to (%s)" % c.get("applies_to")),
                  _bullet("One learning objective", c.get("learning_objective")),
                  _bullet("Screen", c.get("screen")),
                  _bullet("Controls", c.get("controls")),
                  _bullet("On-screen instruction", c.get("instruction")),
                  _bullet("Visuals (same look across the chapter)", c.get("visuals")),
                  _bullet("Feedback", c.get("feedback")),
                  _bullet("Done when", c.get("done_when")),
                  "- **Questions (NCERT only, plus notice prompts on an exploration):**"]
        for q in c.get("question_map") or []:
            tag = "notice" if q["kind"] == "notice" else "NCERT %s" % q.get("ncert_id")
            lines.append("  - [%s] %s" % (tag, q["text"]))
        lines += ["- **Hints:**"]
        for h in c.get("hint_ladder") or []:
            lines.append("  - %s: %s" % (h["rung"], h["text"]))
        lines.append("")
    if len(lines) <= 6:
        lines.append("_This chapter plans no tools._")
    return "\n".join(lines)


def write_briefs(plan, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    made = {}
    for name, fn, kind in (("videos.md", _videos, "video"), ("images.md", _images, "image"),
                           ("tools.md", _tools, "2d_tool")):
        with io.open(os.path.join(out_dir, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(fn(plan) + "\n")
        made[name.split(".")[0]] = len(_nodes(plan, kind))
    return made
